/* 24: 초기 오차가 이미 1% 미만 → 0.4% 미만으로 */
set(24, 2, '원판을 늘려 오차를 0.4% 미만으로 줄이세요.', '오차 = 0\\.[0-3]\\d%');
/* 59: 복귀 감지 신설 문구 */
set(59, 3, '그 점을 다시 끌어와 분리가 풀리는 경계를 확인하세요.', '다시 모두 수염 안');
/* 64: 탐구 문구('명중')와 구분되는 전체 문구로 */
set(64, 3, undefined, '목표 5% 명중');
M[64][2].t = M[64][2].t || '목표 5% 에 정확히 맞추세요.';
/* 65·66: 등식이 상시 표시 → 수동 확인으로 전환 */
set(65, 3, 'P 를 양끝과 가운데 세 곳으로 끌어 두 거리가 늘 같은지 확인하세요.', null);
