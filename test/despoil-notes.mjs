const P = 'src/40-demos.js';
let s = fs.readFileSync(P, 'utf8');
let done = 0, miss = 0;
for (const [fn, subs] of Object.entries(R)) {
  const fi = s.indexOf('function ' + fn + '(root){');
  if (fi < 0) { console.log('데모 없음:', fn); miss++; continue; }
  const fe = s.indexOf('\nfunction ', fi + 10);
  let body = s.slice(fi, fe < 0 ? s.length : fe);
  for (const [key, neu] of subs) {
    // note 블록 중 plain 텍스트가 key 로 시작하는 것을 찾아 내용 교체
    const re = /(class="note"[^>]*>)([\s\S]*?)(<\/div>)/g;
    let m2, found = false, out = '', last = 0;
    while ((m2 = re.exec(body)) !== null) {
      const plain = m2[2].replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
      if (!found && plain.startsWith(key.replace(/\s+/g, ' ').slice(0, 12))) {
        out += body.slice(last, m2.index) + m2[1] + neu + m2[3];
        last = re.lastIndex; found = true;
      }
    }
    if (found) { body = out + body.slice(last); done++; }
    else { console.log('키 미발견:', fn, '|', key.slice(0, 20)); miss++; }
  }
  s = s.slice(0, fi) + body + s.slice(fe < 0 ? s.length : fe);
}
fs.writeFileSync(P, s);
console.log('교체', done, '건 · 실패', miss, '건');
