def set_why(s, no, new):
    """LESSON[no].apply.why 의 문자열 속만 갈아 끼운다."""
    i = s.index('LESSON[%d]={' % no)
    j = s.index('apply:{', i)
    k = s.index("why:'", j) + 5
    e = k
    while True:
        if s[e] == '\\':
            e += 2
            continue
        if s[e] == "'":
            break
        e += 1
    assert "'" not in new, no
    return s[:k] + new + s[e:]


