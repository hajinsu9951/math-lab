def main(path):
    h = open(path, encoding='utf-8').read()
    done, skip = [], []

    # 1) slideShot 틀
    anchor = '/* ---------- 한 문장 강조형 ---------- */'
    if 'function slideShot(' in h:
        skip.append('slideShot 틀')
    else:
        assert h.count(anchor) == 1, 'slideQuote 앞자리를 못 찾음'
        h = h.replace(anchor, HELPER + anchor, 1)
        done.append('slideShot 틀')

    # 2) 화면 5장
    anchor2 = "slideFlow({\n  kicker:'오늘을 관통하는 것',"
    if "kicker:'오늘 여는 화면 ①'" in h:
        skip.append('화면 5장')
    else:
        assert h.count(anchor2) == 1, '「오늘을 관통하는 것」 앞자리를 못 찾음'
        h = h.replace(anchor2, SHOTS + anchor2, 1)
        done.append('화면 5장')

    # 3) 숫자 맞추기
    for name, old, new in EDITS:
        if new in h:
            skip.append(name)
            continue
        assert h.count(old) == 1, '「%s」 자리를 %d 번 찾음' % (name, h.count(old))
        h = h.replace(old, new, 1)
        done.append(name)

    open(path, 'w', encoding='utf-8').write(h)
    print('고침 :', ' · '.join(done) if done else '(없음)')
    print('이미  :', ' · '.join(skip) if skip else '(없음)')


if __name__ == '__main__':
    main(sys.argv[1])
