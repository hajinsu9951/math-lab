  q1.click();
  log.push('①색 ' + getComputedStyle(q1).backgroundColor + ' / ②색 ' + getComputedStyle(q2).backgroundColor);
  log.push('①선택 표시 on: ' + q1.classList.contains('on') + ' · ② on: ' + q2.classList.contains('on'));
